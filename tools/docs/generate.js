#!/usr/bin/env node
// Generates the reference pages of the documentation site from the code:
//   docs/reference/sdk/      TypeDoc, from sdk/index.d.ts and sdk/browser.d.ts
//   docs/reference/program.md  from sdk/lib/idl.json plus the doc comments in lib.rs
// Fails if the IDL and the program source disagree about the instruction set,
// or if an instruction has no documentation.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = path.resolve(__dirname, '../..');
const idl = JSON.parse(fs.readFileSync(path.join(root, 'sdk/lib/idl.json'), 'utf8'));
const librs = fs.readFileSync(path.join(root, 'oblivia-contracts/programs/oblivia-contracts/src/lib.rs'), 'utf8');

function fail(message) {
    console.error(`docs: ${message}`);
    process.exit(1);
}

// --- Instruction docs from lib.rs (`/// ...` directly above `pub fn name(`) ---
function sourceInstructions() {
    const found = new Map();
    const lines = librs.split('\n');
    lines.forEach((line, i) => {
        const match = line.match(/^\s*pub fn (\w+)\(/);
        if (!match) return;
        const docs = [];
        for (let j = i - 1; j >= 0 && /^\s*\/\/\//.test(lines[j]); j--) {
            docs.unshift(lines[j].replace(/^\s*\/\/\/ ?/, ''));
        }
        found.set(match[1], docs.join(' ').trim());
    });
    return found;
}

function typeName(type) {
    if (typeof type === 'string') return type;
    if (type.array) return `[${typeName(type.array[0])}; ${type.array[1]}]`;
    if (type.vec) return `Vec<${typeName(type.vec)}>`;
    if (type.option) return `Option<${typeName(type.option)}>`;
    if (type.defined) return typeof type.defined === 'string' ? type.defined : type.defined.name;
    return JSON.stringify(type);
}

function seedText(seed) {
    if (seed.kind === 'const') {
        const text = Buffer.from(seed.value).toString('utf8');
        return /^[\x20-\x7e]+$/.test(text) ? `"${text}"` : `0x${Buffer.from(seed.value).toString('hex')}`;
    }
    return `${seed.kind} \`${seed.path}\``;
}

function accountRow(account) {
    const flags = [account.writable && 'writable', account.signer && 'signer'].filter(Boolean).join(', ') || 'read-only';
    let derivation = '';
    if (account.address) derivation = `\`${account.address}\``;
    else if (account.pda) derivation = 'PDA: ' + account.pda.seeds.map(seedText).join(', ');
    else if (account.name === 'multisig') derivation = 'PDA: "oblivia_multisig", contract hash, threshold, max signers';
    return `| \`${account.name}\` | ${flags} | ${derivation} |`;
}

function programReference() {
    const docs = sourceInstructions();
    const idlNames = idl.instructions.map(ix => ix.name);
    const missingInIdl = [...docs.keys()].filter(name => !idlNames.includes(name));
    const missingInSource = idlNames.filter(name => !docs.has(name));
    if (missingInIdl.length) fail(`instructions in lib.rs but not in sdk/lib/idl.json: ${missingInIdl.join(', ')}`);
    if (missingInSource.length) fail(`instructions in sdk/lib/idl.json but not in lib.rs: ${missingInSource.join(', ')}`);
    const undocumented = idlNames.filter(name => !docs.get(name));
    if (undocumented.length) fail(`instructions without /// doc comments in lib.rs: ${undocumented.join(', ')}`);

    const out = [
        '# Program instructions',
        '',
        '<!-- Generated by tools/docs/generate.js from sdk/lib/idl.json and lib.rs. Do not edit. -->',
        '',
        `Program \`${idl.address}\` (Devnet). Generated from the program's IDL and source comments, so it always matches the interface the SDK and relay use.`,
        '',
        '!!! note "Pending upgrade"',
        '    The repository contains changes not yet deployed to Devnet (multisig addresses include the agreement settings; the v1 verifier is removed). See the [deployment runbook](../DEPLOYMENT.md).',
        '',
    ];
    // Signing-flow order; anything new appears after these, disabled ones last.
    const flow = ['initialize', 'register_contract', 'verify_groth16_v2', 'create_multisig',
        'record_verified_multisig', 'finalize_multisig', 'verify_signature'];
    const rank = ix => (/^Disabled\./.test(docs.get(ix.name)) ? 1000 : 0) +
        (flow.includes(ix.name) ? flow.indexOf(ix.name) : flow.length);
    const ordered = [...idl.instructions].sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
    for (const ix of ordered) {
        out.push(`## \`${ix.name}\``, '', docs.get(ix.name), '');
        if (ix.args.length) {
            out.push('**Arguments**', '', '| Name | Type |', '| --- | --- |');
            for (const arg of ix.args) out.push(`| \`${arg.name}\` | \`${typeName(arg.type)}\` |`);
            out.push('');
        } else {
            out.push('**Arguments:** none', '');
        }
        out.push('**Accounts**', '', '| Account | Access | Address |', '| --- | --- | --- |');
        for (const account of ix.accounts) out.push(accountRow(account));
        out.push('');
    }
    out.push('## Accounts', '', '| Account | Fields |', '| --- | --- |');
    for (const account of idl.accounts) {
        const type = idl.types.find(t => t.name === account.name);
        const fields = type ? type.type.fields.map(f => `\`${f.name}\`: \`${typeName(f.type)}\``).join(', ') : '';
        out.push(`| \`${account.name}\` | ${fields} |`);
    }
    out.push('', '## Errors', '', '| Code | Name | Message |', '| --- | --- | --- |');
    for (const error of idl.errors) out.push(`| ${error.code} | \`${error.name}\` | ${error.msg} |`);
    out.push('', 'For the Rust items behind these instructions, run `cargo doc -p oblivia-contracts --open` in `oblivia-contracts/`.', '');

    const file = path.join(root, 'docs/reference/program.md');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, out.join('\n'));
    console.log(`docs: wrote ${path.relative(root, file)} (${idl.instructions.length} instructions)`);
}

function sdkReference() {
    const typedoc = path.join(__dirname, 'node_modules/.bin/typedoc');
    if (!fs.existsSync(typedoc)) fail('run `npm ci` in tools/docs first');
    execFileSync(typedoc, ['--options', path.join(__dirname, 'typedoc.json')], { cwd: __dirname, stdio: 'inherit' });
}

programReference();
sdkReference();
