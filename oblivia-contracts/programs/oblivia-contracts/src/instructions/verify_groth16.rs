/// Verify a Groth16 ZK proof on-chain
/// proof_a_neg: negated proof A point (caller must negate before submitting)
/// proof_b: proof B G2 point
/// proof_c: proof C G1 point
/// pub_inputs: [key_commitment, sig_commitment] each 32 bytes
pub fn verify_groth16_handler(
    _ctx: Context<VerifyGroth16>,
    proof_a_neg: [u8; 64],
    proof_b: [u8; 128],
    proof_c: [u8; 64],
    pub_inputs: [u8; 64],
) -> Result<()> {
    let input0: [u8; 32] = pub_inputs[..32].try_into().unwrap();
    let input1: [u8; 32] = pub_inputs[32..].try_into().unwrap();
    let public_inputs = [input0, input1];

    let mut verifier = Groth16Verifier::new(
        &proof_a_neg,
        &proof_b,
        &proof_c,
        &public_inputs,
        &VERIFYING_KEY,
    ).map_err(|_| error!(ObliviaError::InvalidProof))?;

    verifier.verify().map_err(|_| error!(ObliviaError::InvalidProof))?;

    msg!("Groth16 proof verified on-chain!");
    msg!("Key commitment: {:?}", &input0[..8]);
    msg!("Sig commitment: {:?}", &input1[..8]);
    msg!("Identity revealed: false");

    Ok(())
}

#[derive(Accounts)]
pub struct VerifyGroth16<'info> {
    #[account(mut, seeds = [REGISTRY_SEED], bump = registry.bump)]
    pub registry: Account<'info, ContractRegistry>,
    #[account(mut)]
    pub payer: Signer<'info>,
}
